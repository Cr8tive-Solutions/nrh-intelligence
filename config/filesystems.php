    |
    | Supported drivers: "local", "ftp", "sftp", "s3"
    |
    */

    'disks' => [

        // Private storage: payment slips, invoice receipts, candidate documents
        // and client-captured consent evidence. Encrypted at rest under the
        // shared PII_KEY (EncryptedFilesystemAdapter via the `local_mount`
        // driver); no-op while PII_KEY is empty.
        'local' => [
            'driver' => 'local_mount',
            'encrypt' => true,
            'root' => storage_path('app/private'),
            // serve:false — nothing links private files through the framework's
            // /storage route; disabling it removes the signature-gated GET/PUT
            // endpoints into private storage (all downloads go through
            // authenticated, ownership-checked controllers instead).
            'serve' => false,
            'throw' => false,
            'report' => false,
        ],

        'public' => [
            'driver' => 'local',
            'root' => storage_path('app/public'),
            'url' => rtrim(env('APP_URL', 'http://localhost'), '/').'/storage',
            'visibility' => 'public',
            'throw' => false,
            'report' => false,
        ],

        // Read-only view into the admin portal's private storage. Report PDFs
        // are generated by nrh-admin onto its own `local` disk; the client
        // portal serves them to customers through this mount. Mirrors the
        // `client_local` disk on nrh-admin. In production both apps must
        // share (or mount) the same storage — set ADMIN_STORAGE_PATH.
        // `local_mount` (see AppServiceProvider) instead of `local`: the stock
        // local driver creates its root the moment the disk is resolved, so an
        // absent mount threw UnableToCreateDirectory before any code could fall
        // back. Containers never have the sibling path, so that turned a missing
        // mount into a 500 rather than a 404 on a report download.
        //
        // Docker / production MUST set ADMIN_STORAGE_PATH to the shared mount —
        // separate containers have no sibling directory to find.
        'admin_local' => [
            'driver' => 'local_mount',
            'encrypt' => true,
            'root' => env('ADMIN_STORAGE_PATH') ?: base_path('../nrh-admin/storage/app/private'),
            'serve' => false,
            'throw' => false,
            'report' => false,
        ],

        's3' => [
            'driver' => 's3',
            'key' => env('AWS_ACCESS_KEY_ID'),
            'secret' => env('AWS_SECRET_ACCESS_KEY'),
            'region' => env('AWS_DEFAULT_REGION'),
            'bucket' => env('AWS_BUCKET'),
            'url' => env('AWS_URL'),
            'endpoint' => env('AWS_ENDPOINT'),
            'use_path_style_endpoint' => env('AWS_USE_PATH_STYLE_ENDPOINT', false),
            'throw' => false,
            'report' => false,
        ],

    ],

